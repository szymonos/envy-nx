# nx scope/overlay/pin verbs - the "config-shape" surface.
#
# Sourced by nx.sh; expects shared helpers (_nx_apply, _nx_validate_pkg,
# _nx_scope_pkgs, _nx_scopes, _nx_is_init, _nx_read_pkgs) and constants
# (_NX_ENV_DIR) to already be defined.

# Return the sorted, deduplicated list of all scope names: config.nix scopes
# merged with orphaned local_*.nix files discovered on the filesystem.
function _nx_all_scopes() {
  local scopes scopes_dir="$_NX_ENV_DIR/scopes" f lname
  scopes="$(_nx_scopes)"
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    lname="$(basename "$f" .nix)"
    if ! printf '%s\n' "$scopes" | grep -qx "$lname" 2>/dev/null; then
      scopes="${scopes:+$scopes
}$lname"
    fi
  done < <(find "$scopes_dir" -maxdepth 1 -type f -name 'local_*.nix' 2>/dev/null)
  printf '%s\n' "$scopes" | sort
}

# Prints the file of scope id $1, subscribed ids included (nx_overlay.sh).
function _nx_scope_file() {
  _nx_ov_scope_file "$_NX_ENV_DIR" "$1"
}

# Prints "<origin> <file>" for the scope file whose `# scopes:` header names
# standard scope $1, as the last setup run recorded it in overlay_scopes (origin
# local or sub). Fails when no header names it. Setup adds such a scope back on
# every run, so nx points at the header instead of removing it.
function _nx_overlay_owner() {
  local _o _s _f _state="$_NX_ENV_DIR/overlay_scopes"
  [ -f "$_state" ] || return 1
  while read -r _o _s _f; do
    [ "$_o" = org ] && continue
    [ "$_s" = "$1" ] && printf '%s %s\n' "$_o" "$_f" && return 0
  done <"$_state"
  return 1
}

# Rewrite config.nix with the given scope list. Args: scope names to include.
function _nx_write_config() {
  local config_nix="$_NX_ENV_DIR/config.nix"
  local is_init unfree=""
  is_init="$(_nx_is_init)"
  # keep a setup-written allowUnfree, which the flake otherwise reads as false
  [ -f "$config_nix" ] &&
    unfree="$(sed -En 's/^[[:space:]]*allowUnfree[[:space:]]*=[[:space:]]*(true|false);.*/\1/p' "$config_nix")"
  local nix_scopes="" s
  for s in "$@"; do
    nix_scopes+="    \"$s\""$'\n'
  done
  local tmp
  tmp="$(mktemp)"
  cat >"$tmp" <<WRITE_CFG_EOF
# Generated by nx - re-run nix/setup.sh to reconfigure.
{
  isInit = ${is_init:-false};
${unfree:+  allowUnfree = $unfree;
}
  scopes = [
$nix_scopes  ];
}
WRITE_CFG_EOF
  # `command` bypasses any user `alias mv='mv -i'` shadow that would prompt
  # and hang the rebuild (this file is sourced into the interactive shell).
  command mv "$tmp" "$config_nix"
}

# True when a scope file still has the exact shape `nx scope add` generates:
# the `{ pkgs }: with pkgs; [` header, one bare package name per line, and the
# closing bracket. Anything else - a derivation, a `let` block, a comment - is
# hand-written and cannot survive a regenerate-from-package-names rewrite.
function _nx_scope_file_is_generated() {
  local file="$1"
  [ -f "$file" ] || return 1
  # `command` skips a grep function or alias from the interactive shell (ugrep
  # wrappers reject an empty alternative). grep -v exits 1 only when every line
  # matches; 0 (a foreign line) and 2 (an error) must both block the rewrite.
  command grep -qvE '^(\{ pkgs \}: with pkgs; \[\]?|  [a-zA-Z][a-zA-Z0-9_-]*|\])?$' "$file"
  [ $? -eq 1 ] || return 1
  # Every line being allowed is not enough: the header must open the file and a
  # single `]` must close it, or a fragment like `  foo` would pass and be lost.
  local first last
  first="$(head -n 1 "$file")"
  last="$(tail -n 1 "$file")"
  case "$first" in
  '{ pkgs }: with pkgs; []') [ "$last" = "$first" ] ;;
  '{ pkgs }: with pkgs; [')
    [ "$last" = ']' ] && [ "$(command grep -c '^\]$' "$file")" -eq 1 ]
    ;;
  *) return 1 ;;
  esac
}

# Append packages to a local scope .nix file. Caller passes the absolute
# scope file path and the packages to add; we union with the existing
# package list, sort, and rewrite. Returns 1 if nothing actually changed,
# 2 if the file holds hand-written Nix and was left untouched.
function _nx_scope_file_add() {
  local file="$1"
  shift
  # The rewrite below rebuilds the file from parsed package names alone, so any
  # hand-written Nix in it would be dropped without trace. Refuse instead.
  if [ -f "$file" ] && ! _nx_scope_file_is_generated "$file"; then
    printf "\e[31m%s contains hand-written Nix.\e[0m\n" "$file" >&2
    printf "nx cannot add packages without discarding it - edit it instead: \e[1mnx scope edit %s\e[0m\n" \
      "$(basename "$file" .nix)" >&2
    return 2
  fi
  local existing
  existing="$(_nx_scope_pkgs "$file")"
  local all_pkgs=()
  if [ -n "$existing" ]; then
    while IFS= read -r p; do
      all_pkgs+=("$p")
    done <<<"$existing"
  fi
  local p added=false
  for p in "$@"; do
    if printf '%s\n' "${all_pkgs[@]}" | grep -qx "$p" 2>/dev/null; then
      printf "\e[33m%s is already in scope\e[0m\n" "$p" >&2
    else
      all_pkgs+=("$p")
      printf "\e[32madded %s\e[0m\n" "$p" >&2
      added=true
    fi
  done
  [ "$added" = false ] && return 1
  local sorted
  sorted="$(printf '%s\n' "${all_pkgs[@]}" | sort -u)"
  local content="{ pkgs }: with pkgs; ["
  while IFS= read -r p; do
    [ -n "$p" ] && content+=$'\n'"  $p"
  done <<<"$sorted"
  content+=$'\n'"]"$'\n'
  printf '%s' "$content" >"$file"
  return 0
}

function _nx_scope_dispatch() {
  local env_dir="$_NX_ENV_DIR"
  local config_nix="$env_dir/config.nix"
  local scopes_dir="$env_dir/scopes"
  case "${1:-help}" in
  list | ls)
    local scopes
    scopes="$(_nx_all_scopes)"
    if [ -n "$scopes" ]; then
      printf "\e[96mInstalled scopes:\e[0m\n"
      while IFS= read -r s; do
        [ -z "$s" ] && continue
        local display="${s#local_}"
        if [[ "$s" == local_* ]]; then
          printf "  \e[1m*\e[0m %s \e[90m(local)\e[0m\n" "$display"
        else
          printf "  \e[1m*\e[0m %s\n" "$display"
        fi
      done <<<"$scopes"
    else
      printf "\e[33mNo scopes configured.\e[0m Run \e[1mnix/setup.sh\e[0m to initialize.\n"
    fi
    ;;
  show)
    shift
    [ $# -eq 0 ] && {
      echo "Usage: nx scope show <scope>" >&2
      return 1
    }
    local scope_file=""
    case "$1" in
    *[!A-Za-z0-9_/-]*) ;;
    *) scope_file="$(_nx_scope_file "$1")" || scope_file="" ;;
    esac
    if [ ! -f "$scope_file" ]; then
      printf "\e[31mScope '%s' not found.\e[0m\n" "$1" >&2
      return 1
    fi
    printf "\e[96m%s:\e[0m\n" "$1"
    local pkg
    while IFS= read -r pkg; do
      [ -n "$pkg" ] && printf "  \e[1m*\e[0m %s\n" "$pkg"
    done < <(_nx_scope_pkgs "$scope_file" | sort)
    ;;
  tree)
    local scopes s
    if [ -d "$scopes_dir" ]; then
      printf "\e[96mbase:\e[0m\n"
      while IFS= read -r pkg; do
        [ -n "$pkg" ] && printf "  \e[1m*\e[0m %s\n" "$pkg"
      done < <(_nx_scope_pkgs "$scopes_dir/base.nix" | sort)
    fi
    scopes="$(_nx_all_scopes)"
    if [ -n "$scopes" ]; then
      while IFS= read -r s; do
        [ -z "$s" ] && continue
        local display="${s#local_}"
        if [[ "$s" == local_* ]]; then
          printf "\e[96m%s (local):\e[0m\n" "$display"
        else
          printf "\e[96m%s:\e[0m\n" "$display"
        fi
        while IFS= read -r pkg; do
          [ -n "$pkg" ] && printf "  \e[1m*\e[0m %s\n" "$pkg"
        done < <(_nx_scope_pkgs "$(_nx_scope_file "$s")" | sort)
      done <<<"$scopes"
    fi
    local pkgs
    pkgs="$(_nx_read_pkgs)"
    if [ -n "$pkgs" ]; then
      printf "\e[96mextra:\e[0m\n"
      while IFS= read -r pkg; do
        [ -n "$pkg" ] && printf "  \e[1m*\e[0m %s\n" "$pkg"
      done <<<"$pkgs"
    fi
    ;;
  remove | rm)
    shift
    [ $# -eq 0 ] && {
      echo "Usage: nx scope remove <scope> [scope...]" >&2
      return 1
    }
    if [ ! -f "$config_nix" ]; then
      printf "\e[31mNo nix-env config found. Run nix/setup.sh to initialize.\e[0m\n" >&2
      return 1
    fi
    local current_scopes
    current_scopes="$(_nx_scopes)"
    if [ -z "$current_scopes" ]; then
      printf "\e[33mNo scopes configured - nothing to remove.\e[0m\n"
      return 0
    fi
    local ov_dir="$env_dir/local"
    local targets=() own r opted_out=false
    for r in "$@"; do
      # names are joined with spaces below, so only scope-file characters pass
      case "$r" in
      [A-Za-z0-9_-]*/[A-Za-z0-9_-]*)
        case "$r" in */*/* | *[!A-Za-z0-9_/-]*)
          printf "\e[31mInvalid scope name: %s\e[0m\n" "$r" >&2
          continue
          ;;
        esac
        if ! _nx_scope_file "$r" >/dev/null; then
          printf "\e[31m'%s' is not a scope of a subscribed overlay - see nx overlay.\e[0m\n" "$r" >&2
          continue
        fi
        # a subscribed scope stays out across updates until nx scope add brings it back
        if ! command grep -qxF "$r" "$env_dir/overlays.exclude" 2>/dev/null; then
          printf '%s\n' "$r" >>"$env_dir/overlays.exclude" || continue
        fi
        targets+=("$r")
        opted_out=true
        continue
        ;;
      "" | *[!A-Za-z0-9_-]*)
        printf "\e[31mInvalid scope name: %s\e[0m\n" "$r" >&2
        continue
        ;;
      esac
      if [[ "$r" != local_* ]] && own="$(_nx_overlay_owner "$r")"; then
        if [ "${own%% *}" = sub ]; then
          # opted out like an overlay scope: setup runs its remove step once and
          # no longer merges it back from the header; config.nix keeps it until then
          if ! command grep -qxF "$r" "$env_dir/overlays.exclude" 2>/dev/null; then
            printf '%s\n' "$r" >>"$env_dir/overlays.exclude" || continue
          fi
          printf "\e[32m'%s' opted out of the overlays naming it - nx scope add %s brings it back.\e[0m\n" "$r" "$r"
          opted_out=true
        else
          printf "\e[33m'%s' is named in the # scopes: header of %s - remove it there.\e[0m\n" "$r" "${own#* }" >&2
        fi
      else
        targets+=("$r")
      fi
    done
    if [ ${#targets[@]} -eq 0 ]; then
      [ "$opted_out" = true ] || return 1
      _nx_overlay_setup --skip-configure
      return
    fi
    set -- "${targets[@]}"
    local remove_set=" "
    for r in "$@"; do
      remove_set+="$r local_$r "
    done
    local remaining=() removed=false
    while IFS= read -r s; do
      if [[ " $remove_set " == *" $s "* ]]; then
        printf "\e[32mremoved scope: %s\e[0m\n" "${s#local_}"
        removed=true
      else
        remaining+=("$s")
      fi
    done <<<"$current_scopes"
    for r in "$@"; do
      [[ "$r" == */* ]] && continue
      rm -f "$ov_dir/scopes/${r#local_}.nix" "$scopes_dir/local_${r#local_}.nix"
      if [ -f "$scopes_dir/$r.nix" ] && [[ "$r" != local_* ]]; then
        printf "\e[33mNote: '%s' is a base-managed scope - it will be removed from config.nix and re-added on next nix/setup.sh run unless you also pass it to setup.sh --remove\e[0m\n" "$r" >&2
      fi
    done
    for r in "$@"; do
      if [[ " $remove_set " == *" $r "* ]]; then
        local _found=false
        printf '%s\n' "$current_scopes" | grep -qx "$r" 2>/dev/null && _found=true
        printf '%s\n' "$current_scopes" | grep -qx "local_$r" 2>/dev/null && _found=true
        [ "$_found" = false ] && printf "\e[33mscope '%s' is not configured - skipping\e[0m\n" "$r" >&2
      fi
    done
    if [ "$removed" = false ]; then
      return 0
    fi
    _nx_write_config "${remaining[@]}"
    if [ "$opted_out" = true ]; then
      # setup also drops the standard scopes the opted-out file's header named
      _nx_overlay_setup --skip-configure
      return
    fi
    _nx_apply
    printf "Restart your shell to apply changes.\n"
    ;;
  add | create)
    shift
    [ $# -eq 0 ] && {
      echo "Usage: nx scope add <name> [pkg...]" >&2
      return 1
    }
    case "$1" in
    */*)
      if [ $# -gt 1 ] || ! _nx_scope_file "$1" >/dev/null; then
        printf "\e[31m'%s' is not a scope of a subscribed overlay - see nx overlay.\e[0m\n" "$1" >&2
        return 1
      fi
      # the exclusion goes first: an opt-out interrupted before its rebuild leaves
      # the scope in config.nix with the exclusion already written
      if [ -f "$env_dir/overlays.exclude" ]; then
        _nx_overlay_list_set "$env_dir/overlays.exclude" "$1" || return 1
      fi
      if printf '%s\n' "$(_nx_scopes)" | command grep -qxF "$1"; then
        printf "Scope '%s' is already enabled.\n" "$1"
        return 0
      fi
      printf "\e[32mScope '%s' is back in.\e[0m\n" "$1"
      # setup re-enables it with its # scopes: header and runs their installers
      _nx_overlay_setup
      return
      ;;
    esac
    local name="${1//-/_}"
    shift
    # a standard scope opted out of an overlay header comes back through setup
    if [ $# -eq 0 ] && command grep -qxF "$name" "$env_dir/overlays.exclude" 2>/dev/null; then
      _nx_overlay_list_set "$env_dir/overlays.exclude" "$name" || return 1
      printf "\e[32mScope '%s' is back in.\e[0m\n" "$name"
      _nx_overlay_setup
      return
    fi
    case "$name" in
    "" | *[!A-Za-z0-9_]*)
      printf "\e[31mScope names may use only letters, digits, - and _.\e[0m\n" >&2
      return 1
      ;;
    local_*)
      printf "\e[31mScope names cannot start with local_ - setup adds that prefix itself.\e[0m\n" >&2
      return 1
      ;;
    esac
    # Reject overlay names that collide with managed scopes (defined in
    # nix/scopes/<name>.nix and listed in scopes.json:valid_scopes).
    # Without this guard, `nx scope add python` silently creates
    # ~/.config/nix-env/local/scopes/python.nix and adds local_python to
    # config.nix - the shadow then competes with the canonical python scope
    # on the next nix/setup.sh run. Skipped if scopes.json is unavailable
    # (very-first-run before phase_bootstrap_sync_env_dir, or jq missing).
    local _scopes_json
    _scopes_json="$(_nx_find_lib scopes.json 2>/dev/null)" || _scopes_json=""
    if [ -n "$_scopes_json" ] && command -v jq >/dev/null 2>&1; then
      if jq -e --arg n "$name" '.valid_scopes | index($n)' "$_scopes_json" >/dev/null 2>&1; then
        printf "\e[31m'%s' is a managed scope (defined in nix/scopes/%s.nix). Pick a different name for your overlay.\e[0m\n" "$name" "$name" >&2
        return 1
      fi
    fi
    local ov_dir="$env_dir/local"
    local scope_file="$ov_dir/scopes/$name.nix"
    local created=false
    if [ ! -f "$scope_file" ]; then
      mkdir -p "$ov_dir/scopes" "$scopes_dir"
      printf '{ pkgs }: with pkgs; []\n' >"$scope_file"
      command cp "$scope_file" "$scopes_dir/local_$name.nix"
      if [ -f "$config_nix" ]; then
        local current_scopes
        current_scopes="$(_nx_scopes)"
        if ! printf '%s\n' "$current_scopes" | grep -qx "local_$name" 2>/dev/null; then
          local all_scopes=()
          if [ -n "$current_scopes" ]; then
            while IFS= read -r s; do
              all_scopes+=("$s")
            done <<<"$current_scopes"
          fi
          all_scopes+=("local_$name")
          _nx_write_config "${all_scopes[@]}"
        fi
      fi
      created=true
      printf "\e[32mCreated scope '%s' at %s\e[0m\n" "$name" "$scope_file"
    fi
    if [ $# -gt 0 ]; then
      printf "\e[90mvalidating %s...\e[0m\r" "$*"
      local validated=() valid_set p
      valid_set="$(_nx_validate_pkgs "$@")"
      for p in "$@"; do
        if printf '%s\n' "$valid_set" | grep -Fqx "$p" 2>/dev/null; then
          validated+=("$p")
        else
          printf "\e[31m%s not found in nixpkgs\e[0m\n" "$p" >&2
        fi
      done
      if [ ${#validated[@]} -gt 0 ]; then
        local add_rc=0
        _nx_scope_file_add "$scope_file" "${validated[@]}" || add_rc=$?
        case $add_rc in
        0)
          command cp "$scope_file" "$scopes_dir/local_$name.nix"
          _nx_apply
          ;;
        2) return 1 ;;
        esac
      fi
    elif [ "$created" = true ]; then
      printf "Add packages: \e[1mnx scope add %s <pkg> [pkg...]\e[0m\n" "$name"
    else
      printf "\e[33mScope '%s' already exists.\e[0m Add packages: nx scope add %s <pkg>\n" "$name" "$name"
    fi
    ;;
  edit)
    shift
    [ $# -eq 0 ] && {
      echo "Usage: nx scope edit <name>" >&2
      return 1
    }
    case "$1" in
    */*)
      printf "\e[31mInvalid scope name: %s\e[0m\n" "$1" >&2
      return 1
      ;;
    esac
    local name="${1//-/_}"
    local ov_dir="$env_dir/local"
    # a hand-made personal file may keep the hyphens nx would turn into _
    [ -f "$ov_dir/scopes/$name.nix" ] || [ ! -f "$ov_dir/scopes/$1.nix" ] || name="$1"
    local scope_file="$ov_dir/scopes/$name.nix"
    if [ ! -f "$scope_file" ]; then
      if [ -f "$scopes_dir/$name.nix" ]; then
        printf "\e[33mScope '%s' is managed by the base repository and is read-only.\e[0m\n" "$name" >&2
        printf "To customize it, create an overlay scope: \e[1mnx scope add %s <pkg>\e[0m\n" "$name" >&2
        return 1
      fi
      printf "\e[31mScope '%s' not found.\e[0m Create it first: \e[1mnx scope add %s\e[0m\n" "$name" "$name" >&2
      return 1
    fi
    "${EDITOR:-vi}" "$scope_file"
    command cp "$scope_file" "$scopes_dir/local_$name.nix"
    printf "\e[32mSynced scope '%s'.\e[0m Run \e[1mnx upgrade\e[0m to apply.\n" "$name"
    ;;
  *)
    cat <<'EOF'
Usage: nx scope <command> [args]

Commands:
  list                      List enabled scopes
  show <scope>              Show packages in a scope
  tree                      Show all scopes with their packages
  add <name> [pkg...]       Create a scope or add packages to it
  edit <name>               Open a scope file in $EDITOR
  remove <scope> [scope...] Remove one or more scopes
EOF
    ;;
  esac
}

# Runs setup for an overlay or opt-out change. Without a terminal (CI, a script)
# it adds --unattended, so setup's gh login and other prompts never wait forever.
function _nx_overlay_setup() {
  if [ -t 0 ]; then
    _nx_lifecycle_setup "$@"
  else
    _nx_lifecycle_setup "$@" --unattended
  fi
}

# Rewrites overlays.list (or overlays.exclude) without the lines whose first
# field is $2 - or starts with it, when $2 ends in / - appending line $3 when
# given. A read failure leaves the file as it was.
function _nx_overlay_list_set() {
  local file="$1" tmp
  tmp="$(mktemp "$file.XXXXXX")" || return 1
  if [ -e "$file" ] && ! awk -v n="$2" \
    'NF && $1 != n && !(n ~ /\/$/ && index($1, n) == 1)' "$file" >"$tmp"; then
    command rm -f "$tmp"
    printf "\e[31mCould not read %s.\e[0m\n" "$file" >&2
    return 1
  fi
  if [ -n "${3:-}" ] && ! printf '%s\n' "$3" >>"$tmp"; then
    command rm -f "$tmp"
    printf "\e[31mCould not write %s.\e[0m\n" "$file" >&2
    return 1
  fi
  command mv -f "$tmp" "$file"
}

# Prints each subscription in overlays.list as
# "<name>|<overlay>|<ref>|<repo>|<local>|<source>", the source being the clone,
# or the folder itself for a local repository.
function _nx_overlay_subs() {
  local list="$_NX_ENV_DIR/overlays.list" n o r repo p key loc src
  [ -f "$list" ] || return 0
  while read -r n o r repo || [ -n "$n" ]; do
    case "$n" in "" | \#*) continue ;; esac
    [ "$r" = - ] && r=""
    p="$(_nx_ov_parse "$repo" "$r" 2>/dev/null)" || p=""
    key="$(printf '%s' "$p" | cut -d '|' -f 4)"
    loc="$(printf '%s' "$p" | cut -d '|' -f 5)"
    src=""
    if [ "$loc" = true ]; then
      src="$repo"
    elif [ -n "$key" ]; then
      src="$(_nx_ov_cache_dir)/$key"
    fi
    printf '%s|%s|%s|%s|%s|%s\n' "$n" "$o" "$r" "$repo" "$loc" "$src"
  done <"$list"
}

# Makes a relative repository folder absolute, keeping any ?ref= and #<overlay>.
function _nx_overlay_repo_arg() {
  local a="$1" folder
  case "$a" in
  github:* | *://* | *@*:* | /*) ;;
  *)
    folder="${a%%[?#]*}"
    [ -d "$folder" ] && a="$(cd "$folder" && pwd)${a#"$folder"}"
    ;;
  esac
  printf '%s\n' "$a"
}

function _nx_overlay_add() {
  local list="$_NX_ENV_DIR/overlays.list" repo="" ref="" as="" all=false names="" p
  local url pref pname key loc listing interactive=false count o n line existing a b c d
  while [ $# -gt 0 ]; do
    case "$1" in
    --ref | --as)
      [ -n "${2:-}" ] || {
        printf "\e[31m%s requires a value.\e[0m\n" "$1" >&2
        return 1
      }
      if [ "$1" = --ref ]; then ref="$2"; else as="$2"; fi
      shift
      ;;
    --all) all=true ;;
    -*)
      printf "\e[31mUnknown option: %s\e[0m\n" "$1" >&2
      return 1
      ;;
    *)
      if [ -z "$repo" ]; then
        repo="$1"
      else
        names="$names$1
"
      fi
      ;;
    esac
    shift
  done
  if [ -z "$repo" ]; then
    printf "\e[31mUsage: nx overlay add <repo> [overlay...] [--ref <ref>] [--as <name>] [--all]\e[0m\n" >&2
    return 1
  fi
  repo="$(_nx_overlay_repo_arg "$repo")"
  p="$(_nx_ov_parse "$repo" "$ref")" || return 1
  IFS='|' read -r url pref pname key loc <<EOF
$p
EOF
  [ -n "$pname" ] && names="$pname
$names"
  if [ "$all" = true ] && [ -n "$names" ]; then
    printf "\e[31mName overlays or pass --all, not both.\e[0m\n" >&2
    return 1
  fi
  if [ -z "$names" ]; then
    listing="$(_nx_ov_list "$url" "$pref" "$loc")" || return 1
    [ -t 0 ] && interactive=true
    names="$(_nx_ov_choose "$listing" "$all" "$interactive")" || return 1
  fi
  count="$(printf '%s' "$names" | command grep -c .)"
  if [ -n "$as" ] && [ "$count" != 1 ]; then
    printf "\e[31m--as names one overlay - add the others separately.\e[0m\n" >&2
    return 1
  fi
  # check every name before writing any, so a refusal leaves overlays.list as it was
  local new="" explicit="" rc
  while IFS= read -r o; do
    [ -n "$o" ] || continue
    n="${as:-$o}"
    case "$o$n" in *[!A-Za-z0-9_-]*)
      printf "\e[31mInvalid overlay name '%s' - use letters, digits, - and _.\e[0m\n" "$n" >&2
      return 1
      ;;
    esac
    line="$n $o ${pref:--} $url"
    existing=""
    if [ -f "$list" ]; then
      while read -r a b c d || [ -n "$a" ]; do
        [ "$a" = "$n" ] && existing="$b $c $d"
      done <"$list"
    fi
    explicit="$explicit $n"
    if [ "$existing" = "${line#* }" ]; then
      printf "Already subscribed to %s as '%s'.\n" "$o" "$n"
      continue
    fi
    # the same overlay of the same repository may move to another ref;
    # anything else under a taken name would replace a different subscription
    if [ -n "$existing" ] && [ "${existing%% *} ${existing##* }" != "$o $url" ]; then
      printf "\e[31mThe name '%s' already subscribes %s - pick another with --as <name>.\e[0m\n" "$n" "$existing" >&2
      return 1
    fi
    if [ -z "$listing" ]; then
      listing="$(_nx_ov_list "$url" "$pref" "$loc")" || return 1
    fi
    if ! printf '%s\n' "$listing" | cut -f 1 | command grep -qx -- "$o"; then
      printf "\e[31m%s has no overlay %s - see nx overlay browse %s\e[0m\n" "$url" "$o" "$url" >&2
      return 1
    fi
    new="$new$n|$line
"
  done <<EOF
$names
EOF
  while IFS='|' read -r n line; do
    [ -n "$n" ] || continue
    mkdir -p "$_NX_ENV_DIR" && _nx_overlay_list_set "$list" "$n" "$line" || return 1
    printf "\e[32mSubscribed to %s as '%s'.\e[0m\n" "${line#* }" "$n"
  done <<EOF
$new
EOF
  # Setup, not upgrade: a # scopes: header can name a scope with an installer.
  # The names given here count as reviewed and must resolve, as --overlay does.
  export NX_OVERLAY_EXPLICIT="$explicit"
  _nx_overlay_setup
  rc=$?
  unset NX_OVERLAY_EXPLICIT
  return $rc
}

function _nx_overlay_dispatch() {
  local env_dir="$_NX_ENV_DIR"
  case "${1:-}" in
  help | -h)
    cat <<'OVERLAY_HELP'
Usage: nx overlay [add | remove | update | browse]

Show the overlay subscriptions: name, repository, ref, commit and scopes.
  add <repo> [overlay...]  subscribe to overlays by name and apply them
                           --ref <ref>, --as <name> (one overlay), --all
  remove <name...>         drop subscriptions and their scopes
  update                   fetch every subscription and apply the changes (same as nx upgrade)
  browse <repo>            list a repository's overlays and what they are for

<repo> is github:<owner>/<repo>[/<ref>], a git URL (?ref=<ref>), or a local folder.
Without an overlay name: the only overlay, else the one named default, else a picker.
OVERLAY_HELP
    return 0
    ;;
  add)
    shift
    _nx_overlay_add "$@"
    return
    ;;
  remove | rm)
    shift
    local name n o r repo found
    if [ $# -eq 0 ]; then
      printf "\e[31mUsage: nx overlay remove <name...> - see nx overlay for the names.\e[0m\n" >&2
      return 1
    fi
    for name in "$@"; do
      found=false
      if [ -f "$env_dir/overlays.list" ]; then
        while read -r n o r repo || [ -n "$n" ]; do
          [ "$n" = "$name" ] && found=true
        done <"$env_dir/overlays.list"
      fi
      if [ "$found" = false ]; then
        printf "\e[31mNo overlay subscription named '%s' - see nx overlay.\e[0m\n" "$name" >&2
        return 1
      fi
    done
    for name in "$@"; do
      _nx_overlay_list_set "$env_dir/overlays.list" "$name" || return 1
      if [ -f "$env_dir/overlays.exclude" ]; then
        _nx_overlay_list_set "$env_dir/overlays.exclude" "$name/" || return 1
      fi
      printf "\e[32mUnsubscribed from '%s'.\e[0m\n" "$name"
    done
    # setup directly: with no subscription left, nx upgrade would skip the cleanup
    _nx_overlay_setup --skip-configure
    return
    ;;
  update)
    shift
    _nx_pkg_upgrade "$@"
    return
    ;;
  browse)
    shift
    local repo="" ref="" p url pref pname key loc listing n desc
    while [ $# -gt 0 ]; do
      case "$1" in
      --ref)
        [ -n "${2:-}" ] || {
          printf "\e[31m--ref requires a value.\e[0m\n" >&2
          return 1
        }
        ref="$2"
        shift
        ;;
      -*)
        printf "\e[31mUnknown option: %s\e[0m\n" "$1" >&2
        return 1
        ;;
      *)
        [ -z "$repo" ] || {
          printf "\e[31mOne repository at a time.\e[0m\n" >&2
          return 1
        }
        repo="$1"
        ;;
      esac
      shift
    done
    if [ -z "$repo" ]; then
      printf "\e[31mUsage: nx overlay browse <repo> [--ref <ref>]\e[0m\n" >&2
      return 1
    fi
    repo="$(_nx_overlay_repo_arg "$repo")"
    p="$(_nx_ov_parse "$repo" "$ref")" || return 1
    IFS='|' read -r url pref pname key loc <<EOF
$p
EOF
    listing="$(_nx_ov_list "$url" "$pref" "$loc")" || return 1
    printf "\e[96mOverlays in %s%s:\e[0m\n" "$url" "${pref:+ at $pref}"
    while IFS="$(printf '\t')" read -r n desc; do
      [ -n "$n" ] || continue
      printf "  \e[1m%s\e[0m%s\n" "$n" "${desc:+ - $desc}"
    done <<EOF
$listing
EOF
    return 0
    ;;
  "") ;;
  *)
    printf "\e[31mUnknown overlay command: %s\e[0m\n" "$1" >&2
    _nx_overlay_dispatch help >&2
    return 1
    ;;
  esac
  local subs n o r repo loc src head ids id
  subs="$(_nx_overlay_subs)"
  if [ -z "$subs" ]; then
    printf "\e[33mNo overlay subscriptions.\e[0m\n"
    printf "See what a repository offers with \e[1mnx overlay browse <repo>\e[0m, then \e[1mnx overlay add <repo> [overlay]\e[0m.\n"
    return 0
  fi
  while IFS='|' read -r n o r repo loc src; do
    [ -n "$n" ] || continue
    head=""
    if [ "$loc" = true ]; then
      [ -d "$src" ] && head="local folder" || head="local folder missing - the last copy stays in use"
    elif [ -n "$src" ]; then
      head="$(git -C "$src" log -1 --format='%h, committed %cr' 2>/dev/null)" || head=""
    fi
    printf "\e[96m%s\e[0m \e[90m(overlay %s of %s%s)\e[0m\n" "$n" "$o" "$repo" "${r:+ at $r}"
    printf "  %b\n" "${head:-\e[33mnot fetched - run nx upgrade\e[0m}"
    ids=""
    [ -f "$env_dir/overlays/index.nix" ] &&
      ids="$(sed -n "s|^  \"\($n/[^\"]*\)\" = .*|\1|p" "$env_dir/overlays/index.nix")"
    while IFS= read -r id; do
      [ -n "$id" ] || continue
      if command grep -qxF "$id" "$env_dir/overlays.exclude" 2>/dev/null; then
        printf "  \e[1m*\e[0m %s \e[90m(opted out)\e[0m\n" "$id"
      else
        printf "  \e[1m*\e[0m %s\n" "$id"
      fi
    done <<EOF
$ids
EOF
  done <<EOF
$subs
EOF
  return 0
}

function _nx_pin_dispatch() {
  local _pin_file="$_NX_ENV_DIR/pinned_rev"
  case "${1:-show}" in
  set)
    shift
    local _rev="${1:-}"
    if [ -z "$_rev" ]; then
      local _lock="$_NX_ENV_DIR/flake.lock"
      [ -f "$_lock" ] || {
        printf "\e[31mNo flake.lock found - run nx upgrade first.\e[0m\n" >&2
        return 1
      }
      _rev="$(jq -r '.nodes.nixpkgs.locked.rev' "$_lock" 2>/dev/null)" || true
      [ -n "$_rev" ] && [ "$_rev" != "null" ] || {
        printf "\e[31mCould not read nixpkgs revision from flake.lock.\e[0m\n" >&2
        return 1
      }
    fi
    printf '%s\n' "$_rev" >"$_pin_file"
    printf "\e[32mPinned nixpkgs to %s\e[0m\n" "$_rev"
    ;;
  remove | rm)
    if [ -f "$_pin_file" ]; then
      rm "$_pin_file"
      printf "\e[32mPin removed.\e[0m Upgrades will use the CI-validated nixpkgs revision.\n"
    else
      printf "\e[90mNo pin set.\e[0m\n"
    fi
    ;;
  show)
    if [ -f "$_pin_file" ]; then
      printf "\e[96mPinned to:\e[0m %s\n" "$(tr -d '[:space:]' <"$_pin_file")"
    else
      printf "\e[90mNo pin set.\e[0m Upgrades use the CI-validated nixpkgs revision.\n"
    fi
    ;;
  help | *)
    cat <<'PIN_HELP'
Usage: nx pin <command>

Commands:
  set [rev]   Pin nixpkgs to a commit SHA (default: current flake.lock rev)
  remove      Remove the pin (back to the validated revision)
  show        Show current pin status (default)
  help        Show this help

The pin takes effect on the next `nx upgrade` or `nx setup`.
PIN_HELP
    ;;
  esac
}
