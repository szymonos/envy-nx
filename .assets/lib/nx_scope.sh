# nx scope/overlay/pin verbs - the "config-shape" surface.
#
# Sourced by nx.sh; expects shared helpers (_nx_apply, _nx_validate_pkg,
# _nx_scope_pkgs, _nx_scopes, _nx_is_init, _nx_read_pkgs) and constants
# (_NX_ENV_DIR) to already be defined.

# Return the sorted, deduplicated list of all scope names: config.nix scopes
# merged with orphaned local_*.nix files discovered on the filesystem.
function _nx_all_scopes() {
  local scopes scopes_dir="$_NX_ENV_DIR/scopes" f lname
  scopes="$(_nx_scopes)"
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    lname="$(basename "$f" .nix)"
    if ! printf '%s\n' "$scopes" | grep -qx "$lname" 2>/dev/null; then
      scopes="${scopes:+$scopes
}$lname"
    fi
  done < <(find "$scopes_dir" -maxdepth 1 -type f -name 'local_*.nix' 2>/dev/null)
  printf '%s\n' "$scopes" | sort
}

# Prints "<origin> <file>" for the overlay that provides scope $1, as the last
# setup run recorded it in overlay_scopes (origin is org or local). Fails when
# no overlay provides it. Org overlay scopes and header-named scopes are not
# removed or overridden from here (decision 0013).
function _nx_overlay_owner() {
  local _o _s _f _state="$_NX_ENV_DIR/overlay_scopes"
  [ -f "$_state" ] || return 1
  while read -r _o _s _f; do
    [ "$_s" = "$1" ] && printf '%s %s\n' "$_o" "$_f" && return 0
  done <"$_state"
  return 1
}

# Prints the org overlay file that provides any of the given scope ids.
function _nx_org_owner() {
  local id own
  for id in "$@"; do
    own="$(_nx_overlay_owner "$id")" || continue
    [ "${own%% *}" = org ] && printf '%s\n' "${own#* }" && return 0
  done
  return 1
}

# Rewrite config.nix with the given scope list. Args: scope names to include.
function _nx_write_config() {
  local config_nix="$_NX_ENV_DIR/config.nix"
  local is_init
  is_init="$(_nx_is_init)"
  local nix_scopes="" s
  for s in "$@"; do
    nix_scopes+="    \"$s\""$'\n'
  done
  local tmp
  tmp="$(mktemp)"
  cat >"$tmp" <<WRITE_CFG_EOF
# Generated by nx - re-run nix/setup.sh to reconfigure.
{
  isInit = ${is_init:-false};

  scopes = [
$nix_scopes  ];
}
WRITE_CFG_EOF
  # `command` bypasses any user `alias mv='mv -i'` shadow that would prompt
  # and hang the rebuild (this file is sourced into the interactive shell).
  command mv "$tmp" "$config_nix"
}

# True when a scope file still has the exact shape `nx scope add` generates:
# the `{ pkgs }: with pkgs; [` header, one bare package name per line, and the
# closing bracket. Anything else - a derivation, a `let` block, a comment - is
# hand-written and cannot survive a regenerate-from-package-names rewrite.
function _nx_scope_file_is_generated() {
  local file="$1"
  [ -f "$file" ] || return 1
  # `command` skips a grep function or alias from the interactive shell (ugrep
  # wrappers reject an empty alternative). grep -v exits 1 only when every line
  # matches; 0 (a foreign line) and 2 (an error) must both block the rewrite.
  command grep -qvE '^(\{ pkgs \}: with pkgs; \[\]?|  [a-zA-Z][a-zA-Z0-9_-]*|\])?$' "$file"
  [ $? -eq 1 ] || return 1
  # Every line being allowed is not enough: the header must open the file and a
  # single `]` must close it, or a fragment like `  foo` would pass and be lost.
  local first last
  first="$(head -n 1 "$file")"
  last="$(tail -n 1 "$file")"
  case "$first" in
  '{ pkgs }: with pkgs; []') [ "$last" = "$first" ] ;;
  '{ pkgs }: with pkgs; [')
    [ "$last" = ']' ] && [ "$(command grep -c '^\]$' "$file")" -eq 1 ]
    ;;
  *) return 1 ;;
  esac
}

# Append packages to a local scope .nix file. Caller passes the absolute
# scope file path and the packages to add; we union with the existing
# package list, sort, and rewrite. Returns 1 if nothing actually changed,
# 2 if the file holds hand-written Nix and was left untouched.
function _nx_scope_file_add() {
  local file="$1"
  shift
  # The rewrite below rebuilds the file from parsed package names alone, so any
  # hand-written Nix in it would be dropped without trace. Refuse instead.
  if [ -f "$file" ] && ! _nx_scope_file_is_generated "$file"; then
    printf "\e[31m%s contains hand-written Nix.\e[0m\n" "$file" >&2
    printf "nx cannot add packages without discarding it - edit it instead: \e[1mnx scope edit %s\e[0m\n" \
      "$(basename "$file" .nix)" >&2
    return 2
  fi
  local existing
  existing="$(_nx_scope_pkgs "$file")"
  local all_pkgs=()
  if [ -n "$existing" ]; then
    while IFS= read -r p; do
      all_pkgs+=("$p")
    done <<<"$existing"
  fi
  local p added=false
  for p in "$@"; do
    if printf '%s\n' "${all_pkgs[@]}" | grep -qx "$p" 2>/dev/null; then
      printf "\e[33m%s is already in scope\e[0m\n" "$p" >&2
    else
      all_pkgs+=("$p")
      printf "\e[32madded %s\e[0m\n" "$p" >&2
      added=true
    fi
  done
  [ "$added" = false ] && return 1
  local sorted
  sorted="$(printf '%s\n' "${all_pkgs[@]}" | sort -u)"
  local content="{ pkgs }: with pkgs; ["
  while IFS= read -r p; do
    [ -n "$p" ] && content+=$'\n'"  $p"
  done <<<"$sorted"
  content+=$'\n'"]"$'\n'
  printf '%s' "$content" >"$file"
  return 0
}

function _nx_scope_dispatch() {
  local env_dir="$_NX_ENV_DIR"
  local config_nix="$env_dir/config.nix"
  local scopes_dir="$env_dir/scopes"
  case "${1:-help}" in
  list | ls)
    local scopes
    scopes="$(_nx_all_scopes)"
    if [ -n "$scopes" ]; then
      printf "\e[96mInstalled scopes:\e[0m\n"
      while IFS= read -r s; do
        [ -z "$s" ] && continue
        local display="${s#local_}"
        if [[ "$s" == local_* ]]; then
          printf "  \e[1m*\e[0m %s \e[90m(local)\e[0m\n" "$display"
        else
          printf "  \e[1m*\e[0m %s\n" "$display"
        fi
      done <<<"$scopes"
    else
      printf "\e[33mNo scopes configured.\e[0m Run \e[1mnix/setup.sh\e[0m to initialize.\n"
    fi
    ;;
  show)
    shift
    [ $# -eq 0 ] && {
      echo "Usage: nx scope show <scope>" >&2
      return 1
    }
    local scope_file="$scopes_dir/$1.nix"
    if [ ! -f "$scope_file" ]; then
      printf "\e[31mScope '%s' not found.\e[0m\n" "$1" >&2
      return 1
    fi
    printf "\e[96m%s:\e[0m\n" "$1"
    local pkg
    while IFS= read -r pkg; do
      [ -n "$pkg" ] && printf "  \e[1m*\e[0m %s\n" "$pkg"
    done < <(_nx_scope_pkgs "$scope_file" | sort)
    ;;
  tree)
    local scopes s
    if [ -d "$scopes_dir" ]; then
      printf "\e[96mbase:\e[0m\n"
      while IFS= read -r pkg; do
        [ -n "$pkg" ] && printf "  \e[1m*\e[0m %s\n" "$pkg"
      done < <(_nx_scope_pkgs "$scopes_dir/base.nix" | sort)
    fi
    scopes="$(_nx_all_scopes)"
    if [ -n "$scopes" ]; then
      while IFS= read -r s; do
        [ -z "$s" ] && continue
        local display="${s#local_}"
        if [[ "$s" == local_* ]]; then
          printf "\e[96m%s (local):\e[0m\n" "$display"
        else
          printf "\e[96m%s:\e[0m\n" "$display"
        fi
        while IFS= read -r pkg; do
          [ -n "$pkg" ] && printf "  \e[1m*\e[0m %s\n" "$pkg"
        done < <(_nx_scope_pkgs "$scopes_dir/$s.nix" | sort)
      done <<<"$scopes"
    fi
    local pkgs
    pkgs="$(_nx_read_pkgs)"
    if [ -n "$pkgs" ]; then
      printf "\e[96mextra:\e[0m\n"
      while IFS= read -r pkg; do
        [ -n "$pkg" ] && printf "  \e[1m*\e[0m %s\n" "$pkg"
      done <<<"$pkgs"
    fi
    ;;
  remove | rm)
    shift
    [ $# -eq 0 ] && {
      echo "Usage: nx scope remove <scope> [scope...]" >&2
      return 1
    }
    if [ ! -f "$config_nix" ]; then
      printf "\e[31mNo nix-env config found. Run nix/setup.sh to initialize.\e[0m\n" >&2
      return 1
    fi
    local current_scopes
    current_scopes="$(_nx_scopes)"
    if [ -z "$current_scopes" ]; then
      printf "\e[33mNo scopes configured - nothing to remove.\e[0m\n"
      return 0
    fi
    local ov_dir="$env_dir/local"
    local targets=() own r
    for r in "$@"; do
      # names are joined with spaces below, so only scope-file characters pass
      case "$r" in
      "" | *[!A-Za-z0-9_-]*)
        printf "\e[31mInvalid scope name: %s\e[0m\n" "$r" >&2
        continue
        ;;
      esac
      if [[ "$r" != local_* ]] && own="$(_nx_overlay_owner "$r")"; then
        if [ "${own%% *}" = org ]; then
          printf "\e[33m'%s' is controlled by the organization overlay (%s) - not removed.\e[0m\n" "$r" "${own#* }" >&2
        else
          printf "\e[33m'%s' is named in the # scopes: header of %s - remove it there.\e[0m\n" "$r" "${own#* }" >&2
        fi
      elif own="$(_nx_org_owner "local_$r" "local_${r#local_}")"; then
        printf "\e[33m'%s' is controlled by the organization overlay (%s) - not removed.\e[0m\n" "${r#local_}" "$own" >&2
      else
        targets+=("$r")
      fi
    done
    [ ${#targets[@]} -eq 0 ] && return 1
    set -- "${targets[@]}"
    local remove_set=" "
    for r in "$@"; do
      remove_set+="$r local_$r "
    done
    local remaining=() removed=false
    while IFS= read -r s; do
      if [[ " $remove_set " == *" $s "* ]]; then
        printf "\e[32mremoved scope: %s\e[0m\n" "${s#local_}"
        removed=true
      else
        remaining+=("$s")
      fi
    done <<<"$current_scopes"
    for r in "$@"; do
      rm -f "$ov_dir/scopes/${r#local_}.nix" "$scopes_dir/local_${r#local_}.nix"
      if [ -f "$scopes_dir/$r.nix" ] && [[ "$r" != local_* ]]; then
        printf "\e[33mNote: '%s' is a base-managed scope - it will be removed from config.nix and re-added on next nix/setup.sh run unless you also pass it to setup.sh --remove\e[0m\n" "$r" >&2
      fi
    done
    for r in "$@"; do
      if [[ " $remove_set " == *" $r "* ]]; then
        local _found=false
        printf '%s\n' "$current_scopes" | grep -qx "$r" 2>/dev/null && _found=true
        printf '%s\n' "$current_scopes" | grep -qx "local_$r" 2>/dev/null && _found=true
        [ "$_found" = false ] && printf "\e[33mscope '%s' is not configured - skipping\e[0m\n" "$r" >&2
      fi
    done
    if [ "$removed" = false ]; then
      return 0
    fi
    _nx_write_config "${remaining[@]}"
    _nx_apply
    printf "Restart your shell to apply changes.\n"
    ;;
  add | create)
    shift
    [ $# -eq 0 ] && {
      echo "Usage: nx scope add <name> [pkg...]" >&2
      return 1
    }
    local raw="$1" name="${1//-/_}"
    shift
    local own
    if own="$(_nx_org_owner "$name" "local_$name" "local_$raw")"; then
      printf "\e[33m'%s' is provided by the organization overlay (%s) - nothing to add.\e[0m\n" "$raw" "$own"
      return 0
    fi
    case "$name" in
    "" | *[!A-Za-z0-9_]*)
      printf "\e[31mScope names may use only letters, digits, - and _.\e[0m\n" >&2
      return 1
      ;;
    local_*)
      printf "\e[31mScope names cannot start with local_ - setup adds that prefix itself.\e[0m\n" >&2
      return 1
      ;;
    esac
    # Reject overlay names that collide with managed scopes (defined in
    # nix/scopes/<name>.nix and listed in scopes.json:valid_scopes).
    # Without this guard, `nx scope add python` silently creates
    # ~/.config/nix-env/local/scopes/python.nix and adds local_python to
    # config.nix - the shadow then competes with the canonical python scope
    # on the next nix/setup.sh run. Skipped if scopes.json is unavailable
    # (very-first-run before phase_bootstrap_sync_env_dir, or jq missing).
    local _scopes_json
    _scopes_json="$(_nx_find_lib scopes.json 2>/dev/null)" || _scopes_json=""
    if [ -n "$_scopes_json" ] && command -v jq >/dev/null 2>&1; then
      if jq -e --arg n "$name" '.valid_scopes | index($n)' "$_scopes_json" >/dev/null 2>&1; then
        printf "\e[31m'%s' is a managed scope (defined in nix/scopes/%s.nix). Pick a different name for your overlay.\e[0m\n" "$name" "$name" >&2
        return 1
      fi
    fi
    local ov_dir="$env_dir/local"
    local scope_file="$ov_dir/scopes/$name.nix"
    local created=false
    if [ ! -f "$scope_file" ]; then
      mkdir -p "$ov_dir/scopes" "$scopes_dir"
      printf '{ pkgs }: with pkgs; []\n' >"$scope_file"
      command cp "$scope_file" "$scopes_dir/local_$name.nix"
      if [ -f "$config_nix" ]; then
        local current_scopes
        current_scopes="$(_nx_scopes)"
        if ! printf '%s\n' "$current_scopes" | grep -qx "local_$name" 2>/dev/null; then
          local all_scopes=()
          if [ -n "$current_scopes" ]; then
            while IFS= read -r s; do
              all_scopes+=("$s")
            done <<<"$current_scopes"
          fi
          all_scopes+=("local_$name")
          _nx_write_config "${all_scopes[@]}"
        fi
      fi
      created=true
      printf "\e[32mCreated scope '%s' at %s\e[0m\n" "$name" "$scope_file"
    fi
    if [ $# -gt 0 ]; then
      printf "\e[90mvalidating %s...\e[0m\r" "$*"
      local validated=() valid_set p
      valid_set="$(_nx_validate_pkgs "$@")"
      for p in "$@"; do
        if printf '%s\n' "$valid_set" | grep -Fqx "$p" 2>/dev/null; then
          validated+=("$p")
        else
          printf "\e[31m%s not found in nixpkgs\e[0m\n" "$p" >&2
        fi
      done
      if [ ${#validated[@]} -gt 0 ]; then
        local add_rc=0
        _nx_scope_file_add "$scope_file" "${validated[@]}" || add_rc=$?
        case $add_rc in
        0)
          command cp "$scope_file" "$scopes_dir/local_$name.nix"
          _nx_apply
          ;;
        2) return 1 ;;
        esac
      fi
    elif [ "$created" = true ]; then
      printf "Add packages: \e[1mnx scope add %s <pkg> [pkg...]\e[0m\n" "$name"
    else
      printf "\e[33mScope '%s' already exists.\e[0m Add packages: nx scope add %s <pkg>\n" "$name" "$name"
    fi
    ;;
  edit)
    shift
    [ $# -eq 0 ] && {
      echo "Usage: nx scope edit <name>" >&2
      return 1
    }
    case "$1" in
    */*)
      printf "\e[31mInvalid scope name: %s\e[0m\n" "$1" >&2
      return 1
      ;;
    esac
    local name="${1//-/_}"
    local own
    if own="$(_nx_org_owner "$name" "local_$name" "local_$1")"; then
      printf "\e[33m'%s' is controlled by the organization overlay (%s) and cannot be edited here.\e[0m\n" "$1" "$own" >&2
      return 1
    fi
    local ov_dir="$env_dir/local"
    # a hand-made personal file may keep the hyphens nx would turn into _
    [ -f "$ov_dir/scopes/$name.nix" ] || [ ! -f "$ov_dir/scopes/$1.nix" ] || name="$1"
    local scope_file="$ov_dir/scopes/$name.nix"
    if [ ! -f "$scope_file" ]; then
      if [ -f "$scopes_dir/$name.nix" ]; then
        printf "\e[33mScope '%s' is managed by the base repository and is read-only.\e[0m\n" "$name" >&2
        printf "To customize it, create an overlay scope: \e[1mnx scope add %s <pkg>\e[0m\n" "$name" >&2
        return 1
      fi
      printf "\e[31mScope '%s' not found.\e[0m Create it first: \e[1mnx scope add %s\e[0m\n" "$name" "$name" >&2
      return 1
    fi
    "${EDITOR:-vi}" "$scope_file"
    command cp "$scope_file" "$scopes_dir/local_$name.nix"
    printf "\e[32mSynced scope '%s'.\e[0m Run \e[1mnx upgrade\e[0m to apply.\n" "$name"
    ;;
  *)
    cat <<'EOF'
Usage: nx scope <command> [args]

Commands:
  list                      List enabled scopes
  show <scope>              Show packages in a scope
  tree                      Show all scopes with their packages
  add <name> [pkg...]       Create a scope or add packages to it
  edit <name>               Open a scope file in $EDITOR
  remove <scope> [scope...] Remove one or more scopes
EOF
    ;;
  esac
}

# The org overlay path setup will use: NIX_ENV_OVERLAY_DIR, else the path
# saved in overlay_dir by `nx overlay set` or the last setup run.
function _nx_org_overlay_dir() {
  if [ -n "${NIX_ENV_OVERLAY_DIR:-}" ]; then
    printf '%s\n' "$NIX_ENV_OVERLAY_DIR"
  elif [ -f "$_NX_ENV_DIR/overlay_dir" ]; then
    head -n 1 "$_NX_ENV_DIR/overlay_dir"
  fi
}

# Prints "<origin> <dir>" for each overlay directory, the org overlay first.
function _nx_overlay_dirs() {
  local env_dir="$_NX_ENV_DIR" org
  org="$(_nx_org_overlay_dir)"
  [ -n "$org" ] && printf 'org %s\n' "$org"
  if [ -d "$env_dir/local" ] && [ "$env_dir/local" != "$org" ]; then
    printf 'local %s\n' "$env_dir/local"
  fi
}

function _nx_overlay_dispatch() {
  local env_dir="$_NX_ENV_DIR"
  case "${1:-}" in
  help | -h)
    printf "Usage: nx overlay [set <path> | unset]\n\n"
    printf "Show overlay directories, their contents and sync status.\n"
    printf "  set <path>  use <path> as the organization overlay (applied by the next nx setup)\n"
    printf "  unset       stop using the organization overlay (the next nx setup removes its scopes)\n"
    printf "Overlay scopes are listed in \e[1mnx scope list\e[0m (marked 'local').\n"
    return 0
    ;;
  set)
    # not `path`: zsh ties that name to PATH, even as a local
    local ov_path="${2:-}"
    if [ -z "$ov_path" ] || [ ! -d "$ov_path" ] || [ ! -r "$ov_path" ] || [ ! -x "$ov_path" ]; then
      printf "\e[31mUsage: nx overlay set <path> - the path must be a readable directory.\e[0m\n" >&2
      return 1
    fi
    ov_path="$(cd "$ov_path" && pwd)" || return 1
    case "$ov_path" in
    *:* | *"
"*)
      printf "\e[31mThe overlay path cannot contain ':' or a newline.\e[0m\n" >&2
      return 1
      ;;
    esac
    # the same checks setup applies, so a saved path never makes the next setup stop
    if [ -d "$env_dir" ] && [ "$(cd "$ov_path" && pwd -P)" = "$(cd "$env_dir" && pwd -P)" ]; then
      printf "\e[31m%s is the Envy-NX config folder - point to the overlay folder.\e[0m\n" "$ov_path" >&2
      return 1
    fi
    if { [ -e "$ov_path/scopes" ] || [ -L "$ov_path/scopes" ]; } &&
      { [ ! -d "$ov_path/scopes" ] || [ ! -r "$ov_path/scopes" ] || [ ! -x "$ov_path/scopes" ]; }; then
      printf "\e[31m%s/scopes is not a readable directory.\e[0m\n" "$ov_path" >&2
      return 1
    fi
    local tmp=""
    if ! { mkdir -p "$env_dir" && tmp="$(mktemp "$env_dir/overlay_dir.XXXXXX")" &&
      printf '%s\n' "$ov_path" >"$tmp" && command mv -f "$tmp" "$env_dir/overlay_dir"; }; then
      [ -n "$tmp" ] && command rm -f "$tmp"
      printf "\e[31mCould not save %s/overlay_dir.\e[0m\n" "$env_dir" >&2
      return 1
    fi
    printf "\e[32mOrganization overlay set to %s.\e[0m Run \e[1mnx setup\e[0m to apply it.\n" "$ov_path"
    if [ -n "${NIX_ENV_OVERLAY_DIR:-}" ] && [ "$NIX_ENV_OVERLAY_DIR" != "$ov_path" ]; then
      printf "\e[33mNIX_ENV_OVERLAY_DIR=%s is set in this shell and takes precedence.\e[0m\n" "$NIX_ENV_OVERLAY_DIR" >&2
    fi
    return 0
    ;;
  unset)
    if ! rm -f "$env_dir/overlay_dir"; then
      printf "\e[31mCould not remove %s/overlay_dir.\e[0m\n" "$env_dir" >&2
      return 1
    fi
    if [ -n "${NIX_ENV_OVERLAY_DIR:-}" ]; then
      printf "\e[33mNIX_ENV_OVERLAY_DIR=%s is still set and keeps the overlay - remove it from your shell profile too.\e[0m\n" "$NIX_ENV_OVERLAY_DIR" >&2
      return 0
    fi
    printf "Organization overlay forgotten. Run \e[1mnx setup\e[0m to apply - it removes the overlay's scopes.\n"
    return 0
    ;;
  esac
  local dirs
  dirs="$(_nx_overlay_dirs)"
  if [ -z "$dirs" ]; then
    printf "\e[33mNo overlay directory active.\e[0m\n"
    printf "Create one at %s/local/ or point to an organization overlay with \e[1mnx overlay set <path>\e[0m.\n" "$env_dir"
    return 0
  fi
  local scopes_dir="$env_dir/scopes"
  local origin ov_dir label f name indicator hdr own hscopes unknown any_scope=false found
  local scopes_json=""
  command -v jq >/dev/null 2>&1 && scopes_json="$(_nx_find_lib scopes.json 2>/dev/null)" || scopes_json=""
  while read -r origin ov_dir; do
    label="personal"
    [ "$origin" = org ] && label="organization"
    printf "\e[96mOverlay directory:\e[0m %s \e[90m(%s)\e[0m\n" "$ov_dir" "$label"
    if [ ! -d "$ov_dir" ] || [ ! -r "$ov_dir" ]; then
      printf "  \e[31mnot a readable directory - setup stops until it is back, or run nx overlay unset\e[0m\n"
      continue
    fi
    hdr=false
    while IFS= read -r f; do
      [ -n "$f" ] || continue
      [ "$hdr" = false ] && printf "\e[96mScopes:\e[0m\n" && hdr=true
      any_scope=true
      name="$(basename "$f" .nix)"
      indicator=""
      own="$(_nx_overlay_owner "local_$name")" || own=""
      if [ "$origin" = local ] && [ "${own%% *}" = org ]; then
        indicator=" \e[33m(ignored - the organization overlay provides it)\e[0m"
      elif [ ! -f "$scopes_dir/local_$name.nix" ]; then
        indicator=" \e[33m(not synced)\e[0m"
      elif ! cmp -s "$f" "$scopes_dir/local_$name.nix" 2>/dev/null; then
        indicator=" \e[33m(modified)\e[0m"
      fi
      hscopes="$(sed -En 's/^#[[:space:]]*scopes:[[:space:]]*//p' "$f" | head -n 1)"
      if [ -n "$hscopes" ] && [[ "$indicator" != *ignored* ]]; then
        indicator="$indicator \e[90m+ scopes: $hscopes\e[0m"
        # setup skips names scopes.json does not list
        if [ -n "$scopes_json" ]; then
          unknown="$(jq -r --arg h "$hscopes" \
            '[$h | gsub("-"; "_") | splits("[ \t]+") | select(. != "")] - .valid_scopes | join(" ")' \
            "$scopes_json" 2>/dev/null)" || unknown=""
          [ -n "$unknown" ] && indicator="$indicator \e[33m(unknown, ignored: $unknown)\e[0m"
        fi
      fi
      printf "  \e[1m*\e[0m %s%b\n" "$name" "$indicator"
    done < <(find -L "$ov_dir/scopes" -maxdepth 1 -type f -name '*.nix' 2>/dev/null | sort)
    if [ -d "$ov_dir/shell_cfg" ]; then
      hdr=false
      while IFS= read -r f; do
        [ -n "$f" ] || continue
        [ "$hdr" = false ] && printf "\e[96mShell config:\e[0m\n" && hdr=true
        local bname installed
        bname="$(basename "$f")"
        installed="$HOME/.config/shell/overlay/$bname"
        indicator=""
        if [ "$origin" = org ] && [ -f "$env_dir/local/shell_cfg/$bname" ]; then
          indicator=" \e[90m(replaced by the personal overlay's file)\e[0m"
        elif [ -f "$installed" ]; then
          if cmp -s "$f" "$installed" 2>/dev/null; then
            indicator=" \e[32m(synced)\e[0m"
          else
            indicator=" \e[33m(differs)\e[0m"
          fi
        else
          indicator=" \e[33m(not installed)\e[0m"
        fi
        printf "  \e[1m*\e[0m %s%b\n" "$bname" "$indicator"
      done < <(find -L "$ov_dir/shell_cfg" -maxdepth 1 -type f \( -name '*.sh' -o -name '*.bash' -o -name '*.zsh' \) 2>/dev/null)
    fi
    hdr=false
    while IFS= read -r f; do
      [ -n "$f" ] || continue
      [ "$hdr" = false ] && printf "\e[96mHooks:\e[0m\n" && hdr=true
      case "${f#"$ov_dir/hooks/"}" in
      post-setup.d/*/*) indicator=" \e[33m(ignored - only scripts directly in hooks/post-setup.d run)\e[0m" ;;
      post-setup.d/*) indicator=" \e[32m(runs after setup)\e[0m" ;;
      *) indicator=" \e[33m(ignored - only hooks/post-setup.d runs)\e[0m" ;;
      esac
      printf "  \e[1m*\e[0m %s%b\n" "${f#"$ov_dir/"}" "$indicator"
    done < <(find -L "$ov_dir/hooks" -type f -name '*.sh' 2>/dev/null | sort)
  done <<<"$dirs"
  hdr=false
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    name="$(basename "$f" .nix)"
    name="${name#local_}"
    found=false
    while read -r origin ov_dir; do
      [ -f "$ov_dir/scopes/$name.nix" ] && found=true
    done <<<"$dirs"
    [ "$found" = true ] && continue
    [ "$hdr" = false ] && printf "\e[96mSynced scopes without a source:\e[0m\n" && hdr=true
    any_scope=true
    printf "  \e[1m*\e[0m %s \e[33m(source missing)\e[0m\n" "$name"
  done < <(find "$scopes_dir" -maxdepth 1 -type f -name 'local_*.nix' 2>/dev/null | sort)
  [ "$any_scope" = false ] && printf "\e[90mNo overlay scopes.\e[0m\n"
  return 0
}

function _nx_pin_dispatch() {
  local _pin_file="$_NX_ENV_DIR/pinned_rev"
  case "${1:-show}" in
  set)
    shift
    local _rev="${1:-}"
    if [ -z "$_rev" ]; then
      local _lock="$_NX_ENV_DIR/flake.lock"
      [ -f "$_lock" ] || {
        printf "\e[31mNo flake.lock found - run nx upgrade first.\e[0m\n" >&2
        return 1
      }
      _rev="$(jq -r '.nodes.nixpkgs.locked.rev' "$_lock" 2>/dev/null)" || true
      [ -n "$_rev" ] && [ "$_rev" != "null" ] || {
        printf "\e[31mCould not read nixpkgs revision from flake.lock.\e[0m\n" >&2
        return 1
      }
    fi
    printf '%s\n' "$_rev" >"$_pin_file"
    printf "\e[32mPinned nixpkgs to %s\e[0m\n" "$_rev"
    ;;
  remove | rm)
    if [ -f "$_pin_file" ]; then
      rm "$_pin_file"
      printf "\e[32mPin removed.\e[0m Upgrades will use the CI-validated nixpkgs revision.\n"
    else
      printf "\e[90mNo pin set.\e[0m\n"
    fi
    ;;
  show)
    if [ -f "$_pin_file" ]; then
      printf "\e[96mPinned to:\e[0m %s\n" "$(tr -d '[:space:]' <"$_pin_file")"
    else
      printf "\e[90mNo pin set.\e[0m Upgrades use the CI-validated nixpkgs revision.\n"
    fi
    ;;
  help | *)
    cat <<'PIN_HELP'
Usage: nx pin <command>

Commands:
  set [rev]   Pin nixpkgs to a commit SHA (default: current flake.lock rev)
  remove      Remove the pin (back to the validated revision)
  show        Show current pin status (default)
  help        Show this help

The pin takes effect on the next `nx upgrade` or `nx setup`.
PIN_HELP
    ;;
  esac
}
